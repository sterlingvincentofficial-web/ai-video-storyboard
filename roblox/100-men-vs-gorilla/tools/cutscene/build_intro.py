"""Turns tools/cutscene/intro.json (+ the chopper data build_map.py writes to heli.json) into
src/shared/Config/Intro.luau, the game's copy of the intro timeline. The preview studio reads the
JSON directly, so the game and the preview always play the same cutscene.
Run: python3 tools/cutscene/build_intro.py   (after tools/build_map.py)
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.join(ROOT, "tools", "cutscene")
OUT = os.path.join(ROOT, "src", "shared", "Config", "Intro.luau")
KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil", "not",
            "or", "repeat", "return", "then", "true", "until", "while", "continue"}


def key(k):
    return k if k.isidentifier() and k not in KEYWORDS else "[" + json.dumps(k) + "]"


def lua(v, ind=0):
    pad = "\t" * ind
    if isinstance(v, dict):
        items = [f"{pad}\t{key(k)} = {lua(x, ind + 1)}," for k, x in v.items()]
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(v, list):
        if all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v):
            return "{ " + ", ".join(f"{x:g}" for x in v) + " }"
        return "{\n" + "\n".join(f"{pad}\t{lua(x, ind + 1)}," for x in v) + f"\n{pad}}}"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return json.dumps(v)
    return f"{v:g}"


def main():
    data = json.load(open(os.path.join(HERE, "intro.json")))
    heli = json.load(open(os.path.join(HERE, "heli.json")))
    data.pop("_doc", None)
    data["Heli"] = {"scale": heli["scale"], "hub": heli["hub"], "tailHub": heli["tailHub"], "Wreck": heli["wreck"]}
    data["events"].sort(key=lambda e: e["t"])
    with open(OUT, "w") as f:
        f.write("-- Generated by tools/cutscene/build_intro.py from tools/cutscene/intro.json. Do not edit by hand.\n")
        f.write("-- The intro cutscene timeline: camera keys, the chopper's flight, actor tracks, events, poses.\n")
        f.write("return " + lua(data) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
