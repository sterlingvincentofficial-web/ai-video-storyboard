"""Builds the men's gear meshes (one MeshPart each) with Blender (bpy).

Output: assets/men/MenGear.fbx with
  Headband  - band that wraps the head, knot + tails at the back (unit size; the game scales it to the head)
  HandWrap  - boxing wrap shell for an R15 hand (unit size; scaled to each hand)
Run: python tools/blender/build_gear.py   (needs `pip install bpy`)
"""

import math
import os

import bpy
from mathutils import Vector

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "assets", "men")
os.makedirs(OUT, exist_ok=True)


def apply_all(o):
    bpy.context.view_layer.objects.active = o
    o.select_set(True)
    for m in list(o.modifiers):
        bpy.ops.object.modifier_apply(modifier=m.name)
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    for p in o.data.polygons:
        p.use_smooth = True
    o.select_set(False)


def join(name, objs):
    bpy.ops.object.select_all(action="DESELECT")
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]
    bpy.ops.object.join()
    o = bpy.context.active_object
    o.name = o.data.name = name
    cs = [o.matrix_world @ Vector(c) for c in o.bound_box]
    o["model_origin_offset"] = [-(min(c[i] for c in cs) + max(c[i] for c in cs)) / 2 for i in range(3)]
    bpy.ops.object.origin_set(type="ORIGIN_GEOMETRY", center="BOUNDS")
    o.location = (0, 0, 0)
    o.select_set(False)
    return o


def headband():
    # ring: a short tube, a touch wider than the head
    bpy.ops.mesh.primitive_cylinder_add(vertices=48, radius=0.5, depth=0.22)
    ring = bpy.context.active_object
    m = ring.modifiers.new("Shell", "SOLIDIFY")
    m.thickness = 0.05
    m.offset = 1
    bpy.ops.object.modifier_add(type="BEVEL")
    ring.modifiers["Bevel"].width = 0.015
    ring.modifiers["Bevel"].segments = 2
    # delete the caps so it's an open band
    apply_all(ring)
    bpy.context.view_layer.objects.active = ring
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="DESELECT")
    bpy.ops.object.mode_set(mode="OBJECT")
    for p in ring.data.polygons:
        p.select = abs(p.normal.z) > 0.99 and abs(p.center.z) > 0.1 and p.center.xy.length < 0.5
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.delete(type="FACE")
    bpy.ops.object.mode_set(mode="OBJECT")
    # knot at the back (+Y is the back, the model faces -Y)
    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.09, location=(0, 0.56, 0), segments=16, ring_count=8)
    knot = bpy.context.active_object
    knot.scale = (1.2, 0.8, 1)
    apply_all(knot)
    tails = []
    for side in (-1, 1):
        bpy.ops.mesh.primitive_cube_add(size=1, location=(side * 0.08, 0.6, -0.2))
        t = bpy.context.active_object
        t.scale = (0.1, 0.03, 0.36)
        t.rotation_euler = (math.radians(-12), 0, math.radians(side * 14))
        b = t.modifiers.new("Bevel", "BEVEL")
        b.width, b.segments = 0.012, 2
        apply_all(t)
        tails.append(t)
    return join("Headband", [ring, knot] + tails)


def hand_wrap():
    bpy.ops.mesh.primitive_cube_add(size=1)
    o = bpy.context.active_object
    o.scale = (1, 1, 1)
    b = o.modifiers.new("Bevel", "BEVEL")
    b.width, b.segments = 0.14, 4
    apply_all(o)
    # a few raised wrap bands
    bands = []
    for z in (-0.3, 0.0, 0.3):
        bpy.ops.mesh.primitive_cube_add(size=1, location=(0, 0, z))
        band = bpy.context.active_object
        band.scale = (1.04, 1.04, 0.12)
        bb = band.modifiers.new("Bevel", "BEVEL")
        bb.width, bb.segments = 0.05, 3
        apply_all(band)
        bands.append(band)
    return join("HandWrap", [o] + bands)


bpy.ops.wm.read_factory_settings(use_empty=True)
hb = headband()
hw = hand_wrap()
hw.location = (2, 0, 0)
# native bounds so the game can scale the band to any head size, whatever unit the importer picked

lines = ["-- Generated by tools/blender/build_gear.py. Do not edit by hand.",
         "-- Native mesh bounds in studs (Roblox axes). RingCenter is the band's ring centre relative to the bounds centre.",
         "return {"]
for o, has_ring in ((hb, True), (hw, False)):
    corners = [o.matrix_world @ Vector(c) for c in o.bound_box]
    mn = Vector((min(c[i] for c in corners) for i in range(3)))
    mx = Vector((max(c[i] for c in corners) for i in range(3)))
    size, center = mx - mn, (mn + mx) / 2
    entry = "\t%s = { Size = Vector3.new(%.3f, %.3f, %.3f)" % (o.name, size.x, size.z, size.y)
    if has_ring:
        off = Vector(o["model_origin_offset"])  # ring sat at the model origin before recentering
        entry += ", RingCenter = Vector3.new(%.3f, %.3f, %.3f), RingDiameter = 1.0" % (off.x, off.z, off.y)
    lines.append(entry + " },")
lines += ["}", ""]
with open(os.path.join(ROOT, "src", "shared", "RigData", "MenGear.luau"), "w") as f:
    f.write("\n".join(lines))

bpy.ops.object.select_all(action="SELECT")
bpy.ops.export_scene.fbx(filepath=os.path.join(OUT, "MenGear.fbx"), use_selection=True, object_types={"MESH"},
                         apply_unit_scale=True, apply_scale_options="FBX_SCALE_ALL", mesh_smooth_type="FACE")
print("exported", OUT)
