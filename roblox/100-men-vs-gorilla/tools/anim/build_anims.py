"""Turns tools/anim/unit_anims.json into src/shared/Config/UnitAnims.luau (the game's copy).
The preview studio reads the JSON directly, so game and previews always match.
Run: python3 tools/anim/build_anims.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "anim", "unit_anims.json")
OUT = os.path.join(ROOT, "src", "shared", "Config", "UnitAnims.luau")


def lua(v, ind=0):
    pad = "\t" * ind
    if isinstance(v, dict):
        items = [f'{pad}\t{k if k.isidentifier() else "[" + json.dumps(k) + "]"} = {lua(x, ind + 1)},' for k, x in v.items()]
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(v, list):
        if all(isinstance(x, (int, float)) for x in v):
            return "{ " + ", ".join(f"{x:g}" for x in v) + " }"
        return "{\n" + "\n".join(f"{pad}\t{lua(x, ind + 1)}," for x in v) + f"\n{pad}}}"
    if isinstance(v, str):
        return json.dumps(v)
    return f"{v:g}"


data = json.load(open(SRC))
data.pop("_doc", None)
with open(OUT, "w") as f:
    f.write("-- Generated by tools/anim/build_anims.py from tools/anim/unit_anims.json. Do not edit by hand.\n")
    f.write("-- Army combat animation: per attack kind a combat stance, keyframed clips and the clip cycle.\n")
    f.write("-- Joint values: { rx, ry, rz } radians (CFrame.Angles) or { rx, ry, rz, px, py, pz } (Root).\n")
    f.write("return " + lua(data) + "\n")
print("wrote", OUT)
